"""AI rephrasing of questionnaire answers into filing-quality field values.

Three grouped calls (metadata, background, embodiments) return strict JSON.
The model never writes claims, abstract, statutory boilerplate, names, dates
or agent details, and it never touches Word — the deterministic renderer in
`forms.py` consumes the validated values.

Every output is stored as a versioned, editable suggestion: invalid model
output degrades to the raw questionnaire values and never blocks form
generation. Without `AI_API_URL`/`AI_API_KEY`/`AI_MODEL` the stub returns
deterministic values so the whole flow works offline (ADR-004).
"""
from __future__ import annotations

import json
import logging
import re
import time
from urllib.parse import urlparse

import httpx

from app.core.config import settings
from app.services import extraction_store
from app.services.questionnaire_schema import (
    AI_GROUPS,
    FIELD_BY_KEY,
    REQUIRED_FOR_FORMS,
)
from app.services.repository import query_docs

logger = logging.getLogger(__name__)

GROUPS = ("FORM_METADATA", "FORM_BACKGROUND", "FORM_EMBODIMENTS")
GROUP_MAX_TOKENS = {
    "FORM_METADATA": 800,
    "FORM_BACKGROUND": 1200,
    "FORM_EMBODIMENTS": 1800,
}
GROUP_BUDGETS = {
    "FORM_METADATA": 8_000,
    "FORM_BACKGROUND": 8_000,
    "FORM_EMBODIMENTS": 12_000,
}
MAX_AI_ATTEMPTS = 3
FIGURE_MARKER_RE = re.compile(r"^\[\[FIG:([A-Za-z0-9_-]+)\]\]$")

SYSTEM_PROMPT = """\
You are a patent drafting assistant. You rephrase the inventor's supplied facts \
into formal patent prose. You do not give legal advice.
Return ONE JSON object and nothing else. No markdown, no code fences, no commentary.

Rules:
- Use only the supplied material. Never invent patent numbers, prior art, dates, \
people, experimental data, or legal conclusions.
- Plain text. Preserve technical terms, units, reference numerals and names exactly.
- Respect each field's length limit.
- The abstract and claims are generated by the template. Do not rewrite them.
- Short keyword fields are noun phrases: at most 12 words, no trailing period.
- For long-form fields only, place [[FIG:<alias>]] on its own line exactly where a \
figure belongs. Use only aliases from the supplied figure index. Never invent an \
alias or describe pixels you cannot see.
- Long-form fields may be several paragraphs; separate paragraphs with blank lines.
- If a field has no support in the material, return null. Do not pad with filler.
- Do not include a disclaimer; the renderer appends it once at the end.

SCHEMA
{"fields": {"<key>": "<string|null>", ...}, "used_figures": ["<alias>", ...]}
"""


class RefineError(RuntimeError):
    pass


def _provider_configured() -> bool:
    return bool(settings.ai_api_url and settings.ai_api_key and settings.ai_model)


def _post_messages(messages: list[dict], max_tokens: int) -> dict:
    """POST one chat completion with retries; returns the parsed JSON body."""
    if not _provider_configured():
        raise RefineError("AI drafting is not configured.")
    parsed = urlparse(settings.ai_api_url)
    if parsed.scheme != "https" and parsed.hostname not in {"localhost", "127.0.0.1"}:
        raise RefineError("AI_API_URL must use https (http is allowed only for localhost).")
    delay = 2.0
    last_error = "unknown error"
    for _ in range(MAX_AI_ATTEMPTS):
        try:
            response = httpx.post(
                settings.ai_api_url,
                headers={
                    "Authorization": f"Bearer {settings.ai_api_key}",
                    "Content-Type": "application/json",
                },
                json={
                    "model": settings.ai_model,
                    "messages": messages,
                    "temperature": 0.2,
                    "max_tokens": max_tokens,
                },
                timeout=60.0,
            )
        except Exception as exc:
            last_error = f"{type(exc).__name__}: {exc}"[:200]
            time.sleep(delay)
            delay *= 3
            continue
        if response.status_code in (429, 500, 502, 503, 504):
            last_error = f"HTTP {response.status_code}"
            time.sleep(delay)
            delay *= 3
            continue
        if response.status_code == 400 and _vision_rejected(response):
            raise _VisionRejected(response.text[:200])
        try:
            response.raise_for_status()
        except httpx.HTTPStatusError as exc:
            raise RefineError(f"AI request failed with HTTP {exc.response.status_code}.") from exc
        try:
            return response.json()
        except ValueError as exc:
            raise RefineError("AI response was not valid JSON.") from exc
    raise RefineError(f"AI request failed: {last_error}.")


class _VisionRejected(Exception):
    """The provider refused image content; the caller falls back to text."""


def _vision_rejected(response: httpx.Response) -> bool:
    text = (response.text or "").lower()
    return any(
        token in text
        for token in ("image", "vision", "multimodal", "content type", "unsupported")
    )


_VISION_DISABLED = False


def _vision_available() -> bool:
    return bool(settings.ai_vision_enabled and not _VISION_DISABLED)


def select_context(patent_id: str, query: str, max_chars: int) -> tuple[str, list[dict]]:
    """Top-ranked extracted passages plus the usable figure index.

    Paragraphs are scored by keyword overlap with the query and returned in
    document order with file and page. Figures listed are usable, included
    and have an image.
    """
    terms = {
        word.lower()
        for word in re.findall(r"[a-zA-Z0-9]+", query)
        if len(word) > 3
    }
    try:
        files = {
            doc["id"]: doc
            for doc in query_docs("files", filters=[("patent_application_id", "==", patent_id)])
        }
        rows = extraction_store.query_docs(
            "file_extractions", filters=[("patent_application_id", "==", patent_id)]
        )
    except Exception:  # noqa: BLE001 - context is supplementary, not required
        return "", []
    scored: list[tuple[int, str, str, str]] = []
    for row in rows:
        if row.get("status") != extraction_store.READY:
            continue
        file_id = row.get("file_id")
        if not file_id or file_id not in files:
            continue
        try:
            text = extraction_store.read_text(file_id).decode("utf-8", errors="replace")
        except Exception:  # noqa: BLE001 - one bad blob skips one file
            continue
        name = files[file_id].get("original_file_name") or file_id
        for paragraph in re.split(r"\n\s*\n", text):
            paragraph = paragraph.strip()
            if len(paragraph) < 40:
                continue
            words = set(re.findall(r"[a-zA-Z0-9]+", paragraph.lower()))
            overlap = len(words & terms)
            if overlap:
                scored.append((overlap, name, file_id, paragraph))
    scored.sort(key=lambda item: -item[0])
    picked: list[tuple[str, str, str]] = []
    used = 0
    for _, name, file_id, paragraph in scored:
        if used + len(paragraph) > max_chars:
            continue
        picked.append((name, file_id, paragraph))
        used += len(paragraph)
        if used >= max_chars:
            break
    blocks = [f"[{name}]\n{paragraph}" for name, _, paragraph in picked]
    try:
        figure_rows = extraction_store.figures_for_patent(patent_id)
    except Exception:  # noqa: BLE001 - figures are supplementary
        figure_rows = []
    figures = []
    for index, row in enumerate(figure_rows, start=1):
        if (
            row.get("usable") != "usable"
            or not row.get("include_in_drawings", True)
            or not row.get("has_image")
        ):
            continue
        alias = f"fig-{index}"
        figures.append(
            {
                "alias": alias,
                "id": row["id"],
                "label": row.get("label") or alias,
                "caption": row.get("caption") or "",
                "page": row.get("page") or 0,
                "source": files.get(row.get("file_id"), {}).get("original_file_name")
                or "",
            }
        )
    return "\n\n".join(blocks), figures


def _figure_index_block(figures: list[dict]) -> str:
    if not figures:
        return "No usable figures are available; do not emit [[FIG:...]] markers."
    lines = ["Usable figures (reference only by alias):"]
    for figure in figures:
        lines.append(
            f"{figure['alias']}: {figure['label']}"
            + (f" — {figure['caption']}" if figure["caption"] else "")
            + f" ({figure['source'] or 'upload'}"
            + (f", p.{figure['page']}" if figure["page"] else "")
            + ")"
        )
    return "\n".join(lines)


def _short_field_keys(group: str) -> set[str]:
    return {
        key
        for key in AI_GROUPS[group]
        if FIELD_BY_KEY[key].limit <= 500
    }


def validate_group_output(
    group: str, payload: object, figure_aliases: set[str]
) -> tuple[dict[str, str | None], list[str]]:
    """Validate the model JSON; returns (fields, used_figures). Raises."""
    if not isinstance(payload, dict):
        raise RefineError("The model output was not a JSON object.")
    fields = payload.get("fields")
    used = payload.get("used_figures", [])
    if not isinstance(fields, dict):
        raise RefineError("The model output has no 'fields' object.")
    if not isinstance(used, list) or any(not isinstance(item, str) for item in used):
        raise RefineError("The model output has no valid 'used_figures' list.")
    expected = set(AI_GROUPS[group])
    if set(fields) != expected:
        raise RefineError(
            "The model output has wrong keys. Expected: "
            + ", ".join(sorted(expected))
        )
    cleaned: dict[str, str | None] = {}
    for key, value in fields.items():
        limit = FIELD_BY_KEY[key].limit
        if value is None:
            cleaned[key] = None
            continue
        if not isinstance(value, str):
            raise RefineError(f"Field '{key}' must be a string or null.")
        value = value.strip()
        if len(value) > limit:
            raise RefineError(f"Field '{key}' exceeds {limit} characters.")
        if key in _short_field_keys(group) and value:
            words = value.split()
            if len(words) > 12 or value.endswith("."):
                raise RefineError(
                    f"Field '{key}' must be a noun phrase "
                    "(at most 12 words, no trailing period)."
                )
        cleaned[key] = value or None
    markers: set[str] = set()
    if group == "FORM_EMBODIMENTS":
        for key in AI_GROUPS[group]:
            for line in (cleaned.get(key) or "").splitlines():
                match = FIGURE_MARKER_RE.match(line.strip())
                if match:
                    markers.add(match.group(1))
        unknown = markers - figure_aliases
        if unknown:
            raise RefineError(
                "Unknown figure alias(es): " + ", ".join(sorted(unknown)) + "."
            )
    else:
        for key in AI_GROUPS[group]:
            if "[[FIG:" in (cleaned.get(key) or ""):
                raise RefineError(
                    f"Field '{key}' must not contain figure markers "
                    "in the metadata/background groups."
                )
    if set(used) != markers and group == "FORM_EMBODIMENTS":
        raise RefineError("The 'used_figures' list must match the [[FIG:...]] markers.")
    if used and group != "FORM_EMBODIMENTS":
        raise RefineError("'used_figures' must be empty outside embodiments.")
    return cleaned, sorted(markers)


def _stub_fields(group: str, raw: dict[str, str | None]) -> dict[str, str | None]:
    """Deterministic offline values so the flow works without a provider."""
    fields = {}
    for key in AI_GROUPS[group]:
        value = (raw.get(key) or "").strip()
        limit = FIELD_BY_KEY[key].limit
        fields[key] = value[:limit] or None
    return fields


def _figure_payloads(
    figures: list[dict], *, with_images: bool
) -> tuple[list[dict], dict]:
    """Image blocks for the vision call, plus the alias mapping to store."""
    refs = {
        figure["alias"]: {
            "id": figure["id"],
            "label": figure["label"],
            "page": figure["page"],
            "source": figure["source"],
        }
        for figure in figures
    }
    if not with_images:
        return [], refs
    blocks = []
    for figure in figures[: settings.ai_vision_max_images]:
        try:
            image = extraction_store.read_figure_image(
                {"image_blob_id": _blob_id_for(figure["id"])}
            )
        except Exception:  # noqa: BLE001 - one bad blob skips one image
            continue
        import base64

        downsized = _downscale(image, settings.ai_vision_max_edge_px)
        encoded = base64.b64encode(downsized).decode("ascii")
        blocks.append(
            {
                "type": "image_url",
                "image_url": {"url": f"data:image/jpeg;base64,{encoded}"},
            }
        )
    return blocks, refs


def _blob_id_for(figure_id: str) -> str | None:
    row = extraction_store.get_figure(figure_id)
    return (row or {}).get("image_blob_id")


def _downscale(image: bytes, edge: int) -> bytes:
    import cv2
    import numpy as np

    decoded = cv2.imdecode(np.frombuffer(image, np.uint8), cv2.IMREAD_COLOR)
    if decoded is None:
        return image
    height, width = decoded.shape[:2]
    longest = max(height, width)
    if longest > edge:
        scale = edge / longest
        decoded = cv2.resize(
            decoded,
            (max(1, int(width * scale)), max(1, int(height * scale))),
            interpolation=cv2.INTER_AREA,
        )
    ok, buffer = cv2.imencode(".jpg", decoded, [int(cv2.IMWRITE_JPEG_QUALITY), 60])
    return buffer.tobytes() if ok else image


def refine_group(
    patent_id: str,
    profile: dict,
    group: str,
    *,
    raw_values: dict[str, str | None] | None = None,
) -> dict:
    """Refine one group; returns the stored draft payload (never raises)."""
    keys = AI_GROUPS[group]
    raw = raw_values or {}
    budget = GROUP_BUDGETS[group]
    query = " ".join(
        str(raw.get(key) or "") for key in keys
    ) + " " + " ".join(keys).replace("_", " ")
    excerpts, figures = select_context(patent_id, query, budget)
    aliases = {figure["alias"] for figure in figures}

    material = [f"## {FIELD_BY_KEY[key].label}\n{(raw.get(key) or '').strip() or '(not provided)'}" for key in keys]
    user_text = (
        "Refine the following inventor-supplied answers into filing-quality values.\n\n"
        + "\n\n".join(material)
    )
    if excerpts:
        user_text += (
            "\n\nSupporting document excerpts (reference only, never invent from them):\n"
            + excerpts
        )
    user_text += "\n\n" + _figure_index_block(figures)
    messages = [{"role": "system", "content": SYSTEM_PROMPT}]
    with_images = (
        group == "FORM_EMBODIMENTS" and _vision_available() and bool(figures)
    )
    image_blocks, refs = _figure_payloads(figures, with_images=with_images)
    if image_blocks:
        messages.append(
            {
                "role": "user",
                "content": [{"type": "text", "text": user_text}, *image_blocks],
            }
        )
    else:
        messages.append({"role": "user", "content": user_text})

    provider = urlparse(settings.ai_api_url).hostname or "" if _provider_configured() else "stub"
    model = settings.ai_model if _provider_configured() else "stub"
    warnings: list[str] = []
    used: list[str] = []
    if not _provider_configured():
        fields = _stub_fields(group, raw)
        origin = {key: "ai" for key in keys}
        return {
            "fields": fields,
            "origin": origin,
            "figure_refs": refs,
            "provider": "stub",
            "model": "stub",
            "warnings": ["AI is not configured; raw values kept."],
        }
    try:
        body = _post_messages(messages, GROUP_MAX_TOKENS[group])
        payload = _parse_model_json(body)
        fields, used = validate_group_output(group, payload, aliases)
        origin = {key: "ai" for key in keys}
    except _VisionRejected as exc:
        if not with_images:
            raise RefineError(str(exc) or "The provider refused the request.")
        global _VISION_DISABLED
        _VISION_DISABLED = True
        logger.info("vision_disabled", extra={"reason": str(exc)[:120]})
        warnings.append("The provider refused images; refined from text only.")
        return refine_group(patent_id, profile, group, raw_values=raw)
    except RefineError as exc:
        # One repair attempt with the validation error spelled out.
        try:
            repair = _post_messages(
                messages
                + [
                    {
                        "role": "user",
                        "content": f"The previous output was rejected: {exc} "
                        "Return corrected JSON only.",
                    }
                ],
                GROUP_MAX_TOKENS[group],
            )
            fields, used = validate_group_output(
                group, _parse_model_json(repair), aliases
            )
            origin = {key: "ai" for key in keys}
            warnings.append("The first model output was repaired.")
        except RefineError as exc2:
            logger.warning(
                "refine_fallback",
                extra={"group": group, "error_type": type(exc2).__name__},
            )
            fields = _stub_fields(group, raw)
            origin = {key: "fallback" for key in keys}
            warnings.append(f"AI output unusable ({exc2}); raw values kept.")
    return {
        "fields": fields,
        "origin": origin,
        "figure_refs": refs,
        "used_figures": used,
        "provider": provider,
        "model": model,
        "warnings": warnings,
    }


VISION_SYSTEM_PROMPT = """\
You review patent drawing candidates. Return ONE JSON object and nothing else. \
No markdown, no code fences, no commentary.

Rules:
- Describe only what is visible. Never invent details, reference numerals, or \
measurements.
- A patent drawing is a technical sketch, diagram, flowchart, graph, or exploded \
view. Logos, letterhead, decorative banners, and photos of people are not drawings.
- Captions are short: "FIG. n — what it shows".

SCHEMA
{"figures": [{"id": "<figure_id>", "usable": true, "kind": \
"sketch|diagram|flowchart|graph|photo|logo|decoration|irrelevant", \
"confidence": 0.0, "caption": "...", "description": "...", \
"placement": "drawings", "reason": "..."}]}
"""

VISION_KINDS = {
    "sketch",
    "diagram",
    "flowchart",
    "graph",
    "photo",
    "logo",
    "decoration",
    "irrelevant",
}
VISION_BATCH = 4
VISION_MAX_FIGURES = 12


def classify_figures(patent_id: str) -> dict:
    """Vision second opinion over figure candidates. Never raises.

    Only flips screening-rejected rows to usable on confident approval;
    never overrides user approvals or rejections. Stores a description and
    a refined kind for every judged figure.
    """
    from app.services.repository import patch_doc

    if not _vision_available() or not _provider_configured():
        return {"classified": 0, "warning": "Vision is not enabled or configured."}
    try:
        rows = [
            row
            for row in extraction_store.figures_for_patent(patent_id)
            if row.get("has_image")
        ][:VISION_MAX_FIGURES]
    except Exception:  # noqa: BLE001 - classification is supplementary
        return {"classified": 0, "warning": "Figures could not be read."}
    if not rows:
        return {"classified": 0, "warning": "No figures with images to classify."}
    classified = 0
    warnings: list[str] = []
    for start in range(0, len(rows), VISION_BATCH):
        batch = rows[start : start + VISION_BATCH]
        try:
            judged = _classify_batch(batch)
        except _VisionRejected as exc:
            global _VISION_DISABLED
            _VISION_DISABLED = True
            warnings.append("The provider refused images; vision disabled.")
            logger.info("vision_disabled", extra={"reason": str(exc)[:120]})
            break
        except RefineError as exc:
            warnings.append(f"One batch was skipped ({exc}).")
            continue
        for item in judged:
            row = next((row for row in batch if row["id"] == item["id"]), None)
            if row is None:
                continue
            patch: dict = {
                "vision_description": item["description"],
                "vision_caption": item["caption"],
            }
            if item["kind"] in ("sketch", "diagram", "flowchart", "graph"):
                patch["kind"] = item["kind"]
            if (
                row.get("usable") == "rejected"
                and item["usable"]
                and item["confidence"] >= 0.8
                and row.get("reason") != "approved by user"
            ):
                patch["usable"] = "usable"
                patch["reason"] = f"vision approved: {item['reason']}"[:300]
            try:
                patch_doc("file_figures", row["id"], patch)
                classified += 1
            except Exception:  # noqa: BLE001 - one bad row skips one figure
                continue
    result: dict = {"classified": classified}
    if warnings:
        result["warning"] = " ".join(warnings)
    return result


def _classify_batch(rows: list[dict]) -> list[dict]:
    import base64

    content: list[dict] = [
        {
            "type": "text",
            "text": "Judge these patent drawing candidates in order. Their ids: "
            + ", ".join(row["id"] for row in rows),
        }
    ]
    for row in rows:
        try:
            image = extraction_store.read_figure_image(row)
        except Exception:  # noqa: BLE001 - one bad blob skips one image
            continue
        downsized = _downscale(image, settings.ai_vision_max_edge_px)
        encoded = base64.b64encode(downsized).decode("ascii")
        content.append(
            {
                "type": "image_url",
                "image_url": {"url": f"data:image/jpeg;base64,{encoded}"},
            }
        )
    body = _post_messages(
        [
            {"role": "system", "content": VISION_SYSTEM_PROMPT},
            {"role": "user", "content": content},
        ],
        1200,
    )
    payload = _parse_model_json(body)
    if not isinstance(payload, dict) or not isinstance(payload.get("figures"), list):
        raise RefineError("The vision output had no 'figures' list.")
    ids = {row["id"] for row in rows}
    judged = []
    for item in payload["figures"]:
        if not isinstance(item, dict) or item.get("id") not in ids:
            raise RefineError("The vision output named an unknown figure.")
        if not isinstance(item.get("usable"), bool):
            raise RefineError("Vision 'usable' must be true or false.")
        if item.get("kind") not in VISION_KINDS:
            raise RefineError("Vision 'kind' is not a known drawing kind.")
        try:
            confidence = float(item.get("confidence"))
        except (TypeError, ValueError):
            raise RefineError("Vision 'confidence' must be a number.") from None
        if not 0.0 <= confidence <= 1.0:
            raise RefineError("Vision 'confidence' must be between 0 and 1.")
        caption = str(item.get("caption") or "").strip()[:200]
        description = str(item.get("description") or "").strip()[:1000]
        if item.get("placement") != "drawings":
            raise RefineError("Vision 'placement' must be 'drawings'.")
        judged.append(
            {
                "id": item["id"],
                "usable": item["usable"],
                "kind": item["kind"],
                "confidence": confidence,
                "caption": caption,
                "description": description or caption,
                "reason": str(item.get("reason") or "").strip()[:300],
            }
        )
    return judged


def _parse_model_json(body: dict) -> object:
    try:
        content = body["choices"][0]["message"]["content"]
    except (KeyError, IndexError, TypeError) as exc:
        raise RefineError("The AI response had no message content.") from exc
    text = str(content).strip()
    if text.startswith("```"):
        lines = text.splitlines()
        text = "\n".join(
            line for line in lines if not line.strip().startswith("```")
        ).strip()
    try:
        return json.loads(text)
    except ValueError as exc:
        raise RefineError("The AI response was not valid JSON.") from exc


def required_raw_values(questionnaire: dict) -> dict[str, str | None]:
    """Raw values for every required form field, truncated to limits."""
    values = {}
    for key in REQUIRED_FOR_FORMS:
        spec = FIELD_BY_KEY[key]
        value = questionnaire.get(key)
        values[key] = str(value).strip()[: spec.limit] if value not in (None, "") else None
    return values
