"""DOCX assembly and PDF import for generated patent documents.

The built-in layout is always available. When an active `.docx` template
exists for the document type, `docxtpl` renders the documented placeholders
in that template instead (letterhead/layout stays under the template
author's control).

Every stored document is Word format: generated output is always DOCX, and
uploaded PDFs are converted to DOCX with `pdf2docx` before they reach
Firestore. No PDF is ever stored.
"""
import io
import logging
import tempfile
from pathlib import Path

import jinja2
from docx import Document
from docx.shared import Pt, RGBColor
from jinja2.sandbox import SandboxedEnvironment

from app.core.logging import log_event
from app.services.uploads import UploadValidationError, assert_safe_docx

logger = logging.getLogger(__name__)

_JINJA_ENV = SandboxedEnvironment(undefined=jinja2.StrictUndefined)

DOCX_MIME = (
    "application/vnd.openxmlformats-officedocument.wordprocessingml.document"
)

# A conversion runs in-process and cannot be interrupted safely, so bound the
# work before it starts. Patent specifications are well under this.
MAX_PDF_PAGES = 100

SECTION_ORDER = (
    ("ABSTRACT", "Abstract"),
    ("BACKGROUND", "Background"),
    ("SUMMARY", "Summary"),
    ("DESCRIPTION", "Detailed Description"),
    ("CLAIMS", "Claims"),
)

DOCUMENT_TYPES = (
    "Patent Application",
    "Provisional Specification",
    "Complete Specification",
    "PCT Application",
)

KNOWN_PLACEHOLDERS = (
    "TITLE",
    "WATERMARK_TEXT",
    "ABSTRACT",
    "BACKGROUND",
    "SUMMARY",
    "DESCRIPTION",
    "CLAIMS",
)

WATERMARK_TEXT = (
    "DRAFT — NOT LEGAL ADVICE. For professional review only; not for filing as-is."
)

DISCLAIMER = (
    "This document was generated by the Patent Filing & Lifecycle Management "
    "Platform as a drafting aid. It is not legal advice and must be reviewed by "
    "a qualified patent professional before filing."
)


class DocumentGenerationError(RuntimeError):
    pass


# Bundled layout used until an administrator uploads a template for the
# document type. It is the Indian Form 1 application form with the generated
# title and specification placeholders added, so a fresh deployment produces a
# usable document rather than the bare built-in layout.
DEFAULT_TEMPLATE_PATH = (
    Path(__file__).resolve().parent.parent
    / "templates"
    / "Form_1_Patent_Application.docx"
)
_default_template: bytes | None = None
_default_template_loaded = False


def default_template() -> bytes | None:
    """Return the bundled default template, or None when it is unavailable."""
    global _default_template, _default_template_loaded
    if not _default_template_loaded:
        _default_template_loaded = True
        try:
            _default_template = DEFAULT_TEMPLATE_PATH.read_bytes()
        except OSError as exc:
            # A missing bundled file must not break generation: render_docx
            # falls back to the built-in layout.
            logger.warning(
                "default_template_missing",
                extra={"path": str(DEFAULT_TEMPLATE_PATH)},
                exc_info=exc,
            )
            _default_template = None
    return _default_template


def _value(sections: dict, key: str) -> str:
    value = sections.get(key)
    return str(value).strip() if value not in (None, "") else "Not generated."


def build_context(patent: dict, sections: dict) -> dict:
    return {
        "TITLE": patent.get("invention_title") or "Untitled invention",
        "WATERMARK_TEXT": WATERMARK_TEXT,
        "ABSTRACT": _value(sections, "ABSTRACT"),
        "BACKGROUND": _value(sections, "BACKGROUND"),
        "SUMMARY": _value(sections, "SUMMARY"),
        "DESCRIPTION": _value(sections, "DESCRIPTION"),
        "CLAIMS": _value(sections, "CLAIMS"),
    }


def inspect_template(content: bytes) -> tuple[list[str], list[str], str | None]:
    """Return (unknown_placeholders, unused_known_placeholders, parse_error)."""
    try:
        from docxtpl import DocxTemplate

        template = DocxTemplate(io.BytesIO(content))
        used = set(template.get_undeclared_template_variables())
    except Exception as exc:
        return [], [], str(exc)
    unknown = sorted(v for v in used if v not in KNOWN_PLACEHOLDERS)
    unused = sorted(v for v in KNOWN_PLACEHOLDERS if v not in used)
    return unknown, unused, None


def _render_builtin(patent: dict, sections: dict) -> bytes:
    document = Document()

    style = document.styles["Normal"]
    style.font.name = "Calibri"
    style.font.size = Pt(11)

    watermark = document.add_paragraph()
    run = watermark.add_run(WATERMARK_TEXT)
    run.bold = True
    run.font.color.rgb = RGBColor(0xC0, 0x00, 0x00)

    document.add_heading(build_context(patent, sections)["TITLE"], level=0)

    for key, label in SECTION_ORDER:
        document.add_heading(label, level=1)
        for paragraph in _value(sections, key).split("\n\n"):
            document.add_paragraph(paragraph.strip())

    document.add_paragraph()
    disclaimer = document.add_paragraph()
    disclaimer_run = disclaimer.add_run(DISCLAIMER)
    disclaimer_run.italic = True
    disclaimer_run.font.size = Pt(9)
    disclaimer_run.font.color.rgb = RGBColor(0x60, 0x60, 0x60)

    buffer = io.BytesIO()
    document.save(buffer)
    return buffer.getvalue()


def render_docx(patent: dict, sections: dict, template: bytes | None) -> bytes:
    context = build_context(patent, sections)
    if template:
        try:
            assert_safe_docx(template)
        except UploadValidationError as exc:
            raise DocumentGenerationError(
                f"The active DOCX template failed the safety check: {exc}"
            ) from exc
        try:
            from docxtpl import DocxTemplate

            document = DocxTemplate(io.BytesIO(template))
            document.render(context, jinja_env=_JINJA_ENV)
            buffer = io.BytesIO()
            document.save(buffer)
            return buffer.getvalue()
        except jinja2.UndefinedError as exc:
            log_event(
                logger,
                logging.WARNING,
                "docx_template_render_failed",
                error_type=type(exc).__name__,
            )
            raise DocumentGenerationError(
                "The active DOCX template references an unknown "
                f"placeholder: {exc} Ask an administrator to re-upload it."
            ) from exc
        except DocumentGenerationError:
            raise
        except Exception as exc:
            log_event(
                logger,
                logging.WARNING,
                "docx_template_render_failed",
                error_type=type(exc).__name__,
            )
            raise DocumentGenerationError(
                "The active DOCX template could not be rendered. "
                "Ask an administrator to re-upload it."
            ) from exc
    return _render_builtin(patent, sections)


def pdf_to_docx(content: bytes) -> bytes:
    """Convert an uploaded PDF to DOCX entirely in-process.

    `pdf2docx` is a pure-Python dependency (PyMuPDF + python-docx), so this
    works on every deployment target, including serverless hosts without
    LibreOffice. The converted file is validated as a DOCX before it is
    stored, and conversion failures surface as a curated 400 to the caller.
    """
    root = logging.getLogger()
    try:
        import fitz  # PyMuPDF, installed with pdf2docx
    except ImportError as exc:
        raise DocumentGenerationError(
            "PDF import could not be read: PyMuPDF is not installed on this server. Upload a DOCX instead."
        ) from exc
    try:
        with fitz.open(stream=content, filetype="pdf") as pdf:
            if pdf.needs_pass:
                raise DocumentGenerationError(
                    "The PDF is password-protected. Remove the password and "
                    "upload it again."
                )
            pages = pdf.page_count
    except DocumentGenerationError:
        raise
    except Exception as exc:
        raise DocumentGenerationError(
            "The PDF could not be read. It may be damaged or not a real PDF."
        ) from exc
    if pages == 0:
        raise DocumentGenerationError("The PDF has no pages.")
    if pages > MAX_PDF_PAGES:
        raise DocumentGenerationError(
            f"The PDF has {pages} pages; this deployment converts at most "
            f"{MAX_PDF_PAGES} pages per file."
        )

    with tempfile.TemporaryDirectory(prefix="patent-pdf-") as folder:
        source = Path(folder) / "source.pdf"
        target = Path(folder) / "converted.docx"
        source.write_bytes(content)
        # pdf2docx calls logging.basicConfig(level=INFO) at import and logs
        # through the root logger. Restore the level so API logs stay clean.
        previous_level = root.level
        try:
            from pdf2docx import Converter

            root.setLevel(previous_level)
            converter = Converter(str(source))
            try:
                converter.convert(str(target))
            finally:
                converter.close()
        except DocumentGenerationError:
            raise
        except Exception as exc:
            log_event(
                logger,
                logging.WARNING,
                "pdf_conversion_failed",
                error_type=type(exc).__name__,
            )
            raise DocumentGenerationError(
                "The PDF could not be converted to Word. Try a different "
                "PDF, or upload a DOCX instead."
            ) from exc
        finally:
            root.setLevel(previous_level)
        if not target.is_file() or target.stat().st_size == 0:
            raise DocumentGenerationError(
                "The PDF conversion produced no document. Try a different PDF."
            )
        converted = target.read_bytes()

    try:
        assert_safe_docx(converted)
    except UploadValidationError as exc:
        raise DocumentGenerationError(
            "The PDF converted to an unsafe Word document, so it was rejected."
        ) from exc
    return converted
